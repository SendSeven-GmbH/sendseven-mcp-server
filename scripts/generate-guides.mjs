#!/usr/bin/env node
/**
 * Generates src/resources/generated-guides.ts from developer_docs (single
 * source of truth). Run `npm run generate:guides` after editing the guides.
 * The output is committed so the Worker bundle and a public checkout of this
 * folder build without developer_docs. A vitest freshness test fails when the
 * committed file is stale and developer_docs is present.
 *
 *   node scripts/generate-guides.mjs          # write
 *   node scripts/generate-guides.mjs --check  # exit 1 if stale
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const DOCS = resolve(here, "../../developer_docs/docs/guides");
const OUT = resolve(here, "../src/resources/generated-guides.ts");

function clean(md) {
  return md
    .replace(/^---\n[\s\S]*?\n---\n/, "")
    .replace(/^:::(\w+)(?:\[(.*?)\])?\s*$/gm, (_m, kind) => `> **${kind.toUpperCase()}**`)
    .replace(/^:::\s*$/gm, "")
    .replace(/\s\{#[\w-]+\}\s*$/gm, "")
    .replace(/\]\((\.{1,2}\/[^)]*)\)/g, "]($1)")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

function section(md, headingRe) {
  const lines = md.split("\n");
  const start = lines.findIndex((l) => headingRe.test(l));
  if (start < 0) throw new Error(`section not found: ${headingRe}`);
  const level = lines[start].match(/^#+/)[0].length;
  let end = lines.length;
  for (let i = start + 1; i < lines.length; i++) {
    const m = lines[i].match(/^(#+)\s/);
    if (m && m[1].length <= level) { end = i; break; }
  }
  return lines.slice(start, end).join("\n");
}

const read = (p) => clean(readFileSync(resolve(DOCS, p), "utf8"));

const guides = {
  "flow-format-spec": {
    title: "Flow format specification",
    description: "The JSON format of a SendSeven Flow definition: trigger, nodes, edges, entry node, every node type and its fields. Read before writing or editing a flow for validate_flow / save_flow_draft.",
    text: read("flows/flow-format-spec.md"),
  },
  "skills-and-goals": {
    title: "Writing skills and goals",
    description: "How to write a skill (slug, description, mode, body, tool allowlist, attachment instruction), versions, and how to add a structured goal (outputs bound to contact fields, validation, completion actions).",
    text: [read("bots/agents/skills-api.md"), read("bots/agents/skill-goals.md")].join("\n\n---\n\n"),
  },
  "agent-fields": {
    title: "Agent field reference",
    description: "Every field of a Conversational Agent (persona, instructions, model tier, tools, hand-off, language, escalation, skills, knowledge sources), plus the draft and publish rules and the readiness check.",
    text: [read("bots/agents/agents-api.md"), read("bots/agents/drafts-and-publishing.md"), read("bots/agents/readiness.md")].join("\n\n---\n\n"),
  },
  "run-assistant-node": {
    title: "Run AI Assistant node (agents in flows)",
    description: "How a flow starts a Conversational Agent: the run_assistant node, its target, skill/task/output schema and branches.",
    text: [
      read("bots/agents/flows.md"),
      clean(section(readFileSync(resolve(DOCS, "flows/nodes.md"), "utf8"), /^## Run AI Assistant/)),
      clean(section(readFileSync(resolve(DOCS, "flows/flow-format-spec.md"), "utf8"), /^### `run_assistant`/)),
    ].join("\n\n---\n\n"),
  },
};

const out = `/* AUTO-GENERATED by scripts/generate-guides.mjs from developer_docs. Do not edit by hand. */
export interface GeneratedGuide { title: string; description: string; text: string }
export const GENERATED_GUIDES: Record<string, GeneratedGuide> = ${JSON.stringify(guides, null, 2)};
`;

if (process.argv.includes("--check")) {
  const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (cur !== out) { console.error("generated-guides.ts is stale; run npm run generate:guides"); process.exit(1); }
  console.log("generated-guides.ts is up to date");
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT} (${(out.length / 1024).toFixed(0)} KB)`);
}
